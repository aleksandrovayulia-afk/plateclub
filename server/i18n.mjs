const PAT = [
  [/^Не хватает PLT(?: для доплаты)?: (?:нужно|ставка|цена|участие стоит|кейс \S+ стоит) (\d+) PLT, (?:на балансе|доступно) (\d+) PLT\.?$/, (m) => `Not enough PLT: need ${m[1]} PLT, you have ${m[2]} PLT.`],
  [/^Не хватает PLT для доплаты: на балансе (\d+) PLT\.$/, m => `Not enough PLT for the top-up: you have ${m[1]} PLT.`],
  [/^Не хватает PLT/, () => 'Not enough PLT.'],
  [/^Минимальная ставка сейчас (\d+) PLT\.$/, m => `The minimum bid is now ${m[1]} PLT.`],
  [/^Аккаунт заблокирован администратором: (.*)$/, m => `Your account was blocked by an admin: ${m[1]}`],
];
export function tr(msg, lang) {
  if (lang !== 'en' || typeof msg !== 'string') return msg;
  if (EN[msg]) return EN[msg];
  for (const [re, f] of PAT) { const m = msg.match(re); if (m) return f(m); }
  return msg;
}
export function trExtra(extra, lang) {
  if (lang !== 'en' || !extra || !extra.fields) return extra;
  return { ...extra, fields: Object.fromEntries(Object.entries(extra.fields).map(([k, v]) => [k, tr(v, lang)])) };
}
